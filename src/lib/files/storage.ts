import "server-only";
import { createHash, randomBytes } from "node:crypto";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import type { BusinessTx } from "@/lib/db";
import { cleanFileName, UPLOAD_TYPES, extensionOf, uploadProblem } from "./types";

export class UploadError extends Error {}

/**
 * Where file bytes live. Local disk for now (STORAGE_DIR, default
 * ./storage); an S3-compatible driver can implement the same three calls.
 */
interface FileStore {
  put(key: string, bytes: Buffer): Promise<void>;
  get(key: string): Promise<Buffer>;
  remove(key: string): Promise<void>;
}

const ROOT = path.resolve(process.env.STORAGE_DIR || "storage");

/** Keys are generated by us, but check anyway that they can't escape the root. */
function localPath(key: string): string {
  if (!/^[a-zA-Z0-9_-]+(\/[a-zA-Z0-9_.-]+)*$/.test(key) || key.includes("..")) throw new Error("Bad storage key");
  const full = path.resolve(ROOT, key);
  if (!full.startsWith(ROOT + path.sep)) throw new Error("Bad storage key");
  return full;
}

const localStore: FileStore = {
  async put(key, bytes) {
    const full = localPath(key);
    await mkdir(path.dirname(full), { recursive: true });
    await writeFile(full, bytes, { flag: "wx" });
  },
  get: (key) => readFile(localPath(key)),
  remove: (key) => rm(localPath(key), { force: true }),
};

export const fileStore: FileStore = localStore;

/**
 * Save an uploaded file for the business and record it. Validates type and
 * size; the stored name is cleaned and the bytes hashed.
 */
export async function saveUpload(db: BusinessTx, file: File, uploadedById: string | null) {
  const name = cleanFileName(file.name);
  const problem = uploadProblem(name, file.size);
  if (problem) throw new UploadError(problem);
  const bytes = Buffer.from(await file.arrayBuffer());
  const businessId = db.$businessId;
  const storageKey = `${businessId}/${new Date().toISOString().slice(0, 7)}/${randomBytes(16).toString("hex")}.${extensionOf(name)}`;
  await fileStore.put(storageKey, bytes);
  try {
    return await db.storedFile.create({
      data: {
        businessId,
        name,
        contentType: UPLOAD_TYPES[extensionOf(name)].contentType,
        size: bytes.length,
        sha256: createHash("sha256").update(bytes).digest("hex"),
        storageKey,
        uploadedById,
      },
    });
  } catch (e) {
    await fileStore.remove(storageKey);
    throw e;
  }
}

/** Uploaded files from a form field, ignoring the empty entry browsers send when nothing is chosen. */
export const formFiles = (form: FormData, name: string) =>
  form.getAll(name).filter((v): v is File => typeof v === "object" && v !== null && "arrayBuffer" in v && v.size > 0);
